# ROLE / PERMISSION HELPERS
# ============================================================================

def _normalize_values(values) -> set[str]:
    """
    Normalize role/permission values from JWT claims or user objects.
    """

    if values is None:
        return set()

    if isinstance(values, str):
        return {values}

    normalized: set[str] = set()

    for value in values:
        if hasattr(value, "value"):
            normalized.add(str(value.value))
        else:
            normalized.add(str(value))

    return normalized


def require_roles(*required_roles: str) -> Callable:
    """
    Create a dependency requiring one of the supplied roles.

    Example:

        CurrentAdmin = Depends(
            require_roles("admin", "super_admin")
        )
    """

    required = {
        role.lower()
        for role in required_roles
    }

    async def dependency(
        current_user: CurrentUser,
    ):
        user_roles = {
            role.lower()
            for role in _normalize_values(
                current_user.get("roles")
            )
        }

        if not user_roles.intersection(required):
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Insufficient role privileges.",
            )

        return current_user

    return dependency


def require_permission(permission: str | Permission) -> Callable:
    """
    Create a dependency requiring a specific permission.

    Example:

        Depends(require_permission("documents:read"))
    """

    required_permission = (
        permission.value
        if hasattr(permission, "value")
        else str(permission)
    )

    async def dependency(
        current_user: CurrentUser,
    ):
        permissions = _normalize_values(
            current_user.get("permissions")
        )

        roles = {
            role.lower()
            for role in _normalize_values(
                current_user.get("roles")
            )
        }

        # Super administrators bypass individual permission checks.
        if roles.intersection(
            {"super_admin", "superadmin", "system_admin"}
        ):
            return current_user

        if required_permission not in permissions:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=(
                    f"Missing required permission: "
                    f"{required_permission}"
                ),
            )

        return current_user

    return dependency


