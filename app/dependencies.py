def get_request_id(
    request: Request,
    x_request_id: Annotated[str | None, Header()] = None,
) -> str | None:
    """
    Return the request ID generated by request-id middleware.

    Falls back to the X-Request-ID request header when middleware
    has not populated request.state.
    """

    state_request_id = getattr(
        request.state,
        "request_id",
        None,
    )

    return state_request_id or x_request_id


RequestID = Annotated[str | None, Depends(get_request_id)]


