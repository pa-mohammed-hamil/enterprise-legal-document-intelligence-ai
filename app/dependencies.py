async def get_current_user_id(
    current_user: CurrentUser,
) -> str:
    """
    Return the authenticated user's ID.
    """

    user_id = current_user.get("id")

    if not user_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authenticated user ID is unavailable.",
        )

    return str(user_id)


CurrentUserID = Annotated[
    str,
    Depends(get_current_user_id),
]


# ============================================================================
# TENANT / ORGANIZATION
# ============================================================================

async def get_current_organization_id(
    current_user: CurrentUser,
    request: Request,
) -> str:
    """
    Resolve the organization/tenant ID for the authenticated user.

    Tenant isolation is mandatory when MULTI_TENANT_ENABLED is enabled.
    """

    organization_id = current_user.get("organization_id")

    if not organization_id:
        organization_id = getattr(
            request.state,
            "organization_id",
            None,
        )

    if settings.MULTI_TENANT_ENABLED and not organization_id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Organization context is required.",
        )

    return str(organization_id) if organization_id else ""


CurrentOrganizationID = Annotated[
    str,
    Depends(get_current_organization_id),
]


