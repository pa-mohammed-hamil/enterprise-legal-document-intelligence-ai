def _extract_bearer_token(
    authorization: str | None,
) -> str:
    """
    Extract a Bearer token from the Authorization header.
    """

    if not authorization:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication required.",
            headers={"WWW-Authenticate": "Bearer"},
        )

    scheme, _, token = authorization.partition(" ")

    if scheme.lower() != "bearer" or not token:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid authentication scheme.",
            headers={"WWW-Authenticate": "Bearer"},
        )

    return token.strip()


async def get_current_user(
    request: Request,
    authorization: Annotated[str | None, Header()] = None,
):
    """
    Resolve the authenticated user from the JWT access token.

    Authentication middleware may already have populated
    request.state.user. In that case, reuse the resolved user.
    """

    state_user = getattr(
        request.state,
        "user",
        None,
    )

    if state_user is not None:
        return state_user

    token = _extract_bearer_token(authorization)

    try:
        payload = decode_access_token(token)
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired access token.",
            headers={"WWW-Authenticate": "Bearer"},
        ) from exc

    if not payload:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid access token.",
            headers={"WWW-Authenticate": "Bearer"},
        )

    user_id = (
        payload.get("sub")
        or payload.get("user_id")
        or payload.get("id")
    )

    if not user_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Access token does not contain a user identity.",
            headers={"WWW-Authenticate": "Bearer"},
        )

    # Authentication middleware/service is responsible for resolving
    # the complete user object. Until then, expose the verified claims.
    user = {
        "id": user_id,
        "organization_id": payload.get("organization_id"),
        "email": payload.get("email"),
        "roles": payload.get("roles", []),
        "permissions": payload.get("permissions", []),
        "token_payload": payload,
    }

    request.state.user = user

    return user


CurrentUser = Annotated[dict, Depends(get_current_user)]


# ============================================================================
# OPTIONAL USER
# ============================================================================

async def get_optional_user(
    request: Request,
    authorization: Annotated[str | None, Header()] = None,
):
    """
    Resolve the authenticated user when credentials are supplied.

    Returns None instead of raising an authentication error.
    Useful for endpoints that support both anonymous and authenticated
    access.
    """

    if not authorization:
        return None

    try:
        return await get_current_user(
            request=request,
            authorization=authorization,
        )
    except HTTPException:
        return None


OptionalUser = Annotated[
    dict | None,
    Depends(get_optional_user),
]


