async def require_document_access(
    current_user: CurrentUser,
):
    """
    Base dependency for document-level authorization.

    Individual document repositories/services should additionally
    enforce ownership, organization membership, ACLs, and document
    classification restrictions.
    """

    if not current_user.get("id"):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authenticated user required.",
        )

    return current_user


DocumentAccessUser = Annotated[
    dict,
    Depends(require_document_access),
]


