# SECURITY CONTEXT
# ============================================================================

def get_security_context(
    request: Request,
    current_user: CurrentUser,
):
    """
    Build a normalized security context for downstream services,
    audit logging, RAG permission filters, and agents.
    """

    return {
        "user_id": current_user.get("id"),
        "organization_id": current_user.get(
            "organization_id"
        ),
        "roles": current_user.get("roles", []),
        "permissions": current_user.get(
            "permissions",
            [],
        ),
        "request_id": getattr(
            request.state,
            "request_id",
            None,
        ),
        "ip_address": getattr(
            request.client,
            "host",
            None,
        )
        if request.client
        else None,
        "tenant_isolation": (
            settings.ENABLE_TENANT_ISOLATION
        ),
    }


SecurityContext = Annotated[
    dict,
    Depends(get_security_context),
]


