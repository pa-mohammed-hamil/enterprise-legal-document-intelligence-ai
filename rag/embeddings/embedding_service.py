class CacheBackend(str, Enum):
    MEMORY = "memory"
    REDIS = "redis"
    HYBRID = "hybrid"


class CacheStatus(str, Enum):
    HIT = "hit"
    MISS = "miss"
    EXPIRED = "expired"
    ERROR = "error"


@dataclass(slots=True)
class EmbeddingCacheConfig:
    """
    Configuration for the embedding cache.

    Cache keys include:
        text hash
        model name
        model version
        embedding dimension
        normalization flag
        namespace

    This prevents embeddings generated by different models or model
    versions from accidentally sharing the same cache entry.
    """

    backend: CacheBackend = CacheBackend.MEMORY

    namespace: str = "legal-ai:embeddings"

    ttl_seconds: int = 7 * 24 * 60 * 60

    memory_max_entries: int = 10_000

    redis_key_prefix: str = "embedding"

    enable_memory_lru: bool = True

    cache_empty_text: bool = False

    validate_dimension: bool = True

    normalize_text_for_key: bool = False

    include_model_version: bool = True

    compression_enabled: bool = False

    fail_open: bool = True


@dataclass(slots=True)
class EmbeddingCacheEntry:
    key: str

    embedding: list[float]

    text_hash: str

    model_name: str
    model_version: Optional[str] = None

    dimension: Optional[int] = None

    normalized: bool = False

    created_at: float = field(
        default_factory=time.time
    )

    expires_at: Optional[float] = None

    metadata: dict[str, Any] = field(
        default_factory=dict
    )

    @property
    def expired(self) -> bool:
        return (
            self.expires_at is not None
            and time.time() >= self.expires_at
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "key": self.key,
            "embedding": self.embedding,
            "text_hash": self.text_hash,
            "model_name": self.model_name,
            "model_version": self.model_version,
            "dimension": self.dimension,
            "normalized": self.normalized,
            "created_at": self.created_at,
            "expires_at": self.expires_at,
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(
        cls,
        value: dict[str, Any],
    ) -> "EmbeddingCacheEntry":
        return cls(
            key=str(value["key"]),
            embedding=[
                float(item)
                for item in value[
                    "embedding"
                ]
            ],
            text_hash=str(
                value["text_hash"]
            ),
            model_name=str(
                value["model_name"]
            ),
            model_version=(
                value.get(
                    "model_version"
                )
            ),
            dimension=(
                int(value["dimension"])
                if value.get("dimension")
                is not None
                else None
            ),
            normalized=bool(
                value.get(
                    "normalized",
                    False,
                )
            ),
            created_at=float(
                value.get(
                    "created_at",
                    time.time(),
                )
            ),
            expires_at=(
                float(
                    value["expires_at"]
                )
                if value.get(
                    "expires_at"
                )
                is not None
                else None
            ),
            metadata=dict(
                value.get(
                    "metadata",
                    {},
                )
            ),
        )


@dataclass(slots=True)
class CacheLookupResult:
    status: CacheStatus

    key: str

    embedding: Optional[
        list[float]
    ] = None

    entry: Optional[
        EmbeddingCacheEntry
    ] = None

    source: Optional[str] = None

    latency_ms: float = 0.0

    error: Optional[str] = None

    @property
    def hit(self) -> bool:
        return (
            self.status
            == CacheStatus.HIT
        )


@dataclass(slots=True)
class BatchCacheLookup:
    embeddings: list[
        Optional[list[float]]
    ]

    missing_indices: list[int]

    keys: list[str]

    hits: int = 0
    misses: int = 0

    metadata: dict[str, Any] = field(
        default_factory=dict
    )


@dataclass(slots=True)
class EmbeddingCacheStats:
    hits: int = 0
    misses: int = 0
    expired: int = 0
    writes: int = 0
    deletes: int = 0
    errors: int = 0

    memory_entries: int = 0

    @property
    def requests(self) -> int:
        return (
            self.hits
            + self.misses
            + self.expired
        )

    @property
    def hit_rate(self) -> float:
        total = self.requests

        if total == 0:
            return 0.0

        return self.hits / total

    def to_dict(self) -> dict[str, Any]:
        return {
            "hits": self.hits,
            "misses": self.misses,
            "expired": self.expired,
            "writes": self.writes,
            "deletes": self.deletes,
            "errors": self.errors,
            "requests": self.requests,
            "hit_rate": self.hit_rate,
            "memory_entries":
                self.memory_entries,
        }


class RedisLike(Protocol):
    """
    Minimal Redis interface required by this cache.

    redis.asyncio is intentionally not assumed here because embedding
    generation in this layer is synchronous. An async cache can be
    added separately if the embedding service becomes async.
    """

    def get(
        self,
        key: str,
    ) -> Any:
        ...

    def set(
        self,
        key: str,
        value: Any,
        ex: Optional[int] = None,
    ) -> Any:
        ...

    def delete(
        self,
        *keys: str,
    ) -> Any:
        ...


class EmbeddingCacheError(Exception):
    def __init__(
        self,
        message: str,
        *,
        code: str = (
            "EMBEDDING_CACHE_ERROR"
        ),
        cause: Optional[
            Exception
        ] = None,
    ) -> None:
        super().__init__(message)

        self.code = code
        self.cause = cause


class EmbeddingCache:
    """
    Production-oriented cache for document/query embeddings.

    Supported modes
    ---------------

    MEMORY
        Process-local LRU cache.

    REDIS
        Distributed cache.

    HYBRID
        L1 memory + L2 Redis.

    Recommended production topology:

        EmbeddingService
              ↓
        EmbeddingCache
          ┌───┴────┐
          ↓        ↓
      L1 Memory  L2 Redis
          ↓        ↓
          └────┬───┘
               ↓
        HuggingFace Model

    Cache misses invoke the embedding model in EmbeddingService,
    not inside this class. Keeping model inference outside the cache
    prevents cache infrastructure from owning model lifecycle.
    """

    def __init__(
        self,
        config: Optional[
            EmbeddingCacheConfig
        ] = None,
        *,
        redis_client: Optional[
            RedisLike
        ] = None,
    ) -> None:

        self.config = (
            config
            or EmbeddingCacheConfig()
        )

        self.redis = redis_client

        self._memory: OrderedDict[
            str,
            EmbeddingCacheEntry,
        ] = OrderedDict()

        self._lock = threading.RLock()

        self._stats = (
            EmbeddingCacheStats()
        )

        self._validate_config()

    # ==========================================================
    # Public lookup
    # ==========================================================

    def get(
        self,
        text: str,
        *,
        model_name: str,
        model_version: Optional[
            str
        ] = None,
        dimension: Optional[
            int
        ] = None,
        normalized: bool = False,
        namespace: Optional[
            str
        ] = None,
    ) -> CacheLookupResult:

        started = time.perf_counter()

        key = self.build_key(
            text,
            model_name=model_name,
            model_version=model_version,
            dimension=dimension,
            normalized=normalized,
            namespace=namespace,
        )

        if (
            not text
            and not self.config
            .cache_empty_text
        ):
            self._stats.misses += 1

            return CacheLookupResult(
                status=CacheStatus.MISS,
                key=key,
                latency_ms=self._elapsed(
                    started
                ),
            )

        try:
            # ----------------------------------------------
            # L1 memory
            # ----------------------------------------------

            if self.config.backend in {
                CacheBackend.MEMORY,
                CacheBackend.HYBRID,
            }:
                entry = (
                    self._memory_get(
                        key
                    )
                )

                if entry is not None:
                    validation = (
                        self._validate_entry(
                            entry,
                            model_name=(
                                model_name
                            ),
                            model_version=(
                                model_version
                            ),
                            dimension=dimension,
                            normalized=(
                                normalized
                            ),
                        )
                    )

                    if validation:
                        self._stats.hits += 1

                        return (
                            CacheLookupResult(
                                status=(
                                    CacheStatus
                                    .HIT
                                ),
                                key=key,
                                embedding=list(
                                    entry
                                    .embedding
                                ),
                                entry=entry,
                                source="memory",
                                latency_ms=(
                                    self._elapsed(
                                        started
                                    )
                                ),
                            )
                        )

                    self._memory_delete(
                        key
                    )

            # ----------------------------------------------
            # L2 Redis
            # ----------------------------------------------

            if self.config.backend in {
                CacheBackend.REDIS,
                CacheBackend.HYBRID,
            }:
                entry = (
                    self._redis_get(
                        key
                    )
                )

                if entry is not None:
                    if entry.expired:
                        self._stats.expired += 1

                        self._redis_delete(
                            key
                        )

                        return (
                            CacheLookupResult(
                                status=(
                                    CacheStatus
                                    .EXPIRED
                                ),
                                key=key,
                                source="redis",
                                latency_ms=(
                                    self._elapsed(
                                        started
                                    )
                                ),
                            )
                        )

                    if not self._validate_entry(
                        entry,
                        model_name=model_name,
                        model_version=(
                            model_version
                        ),
                        dimension=dimension,
                        normalized=normalized,
                    ):
                        self._redis_delete(
                            key
                        )

                        self._stats.misses += 1

                        return (
                            CacheLookupResult(
                                status=(
                                    CacheStatus
                                    .MISS
                                ),
                                key=key,
                                source="redis",
                                latency_ms=(
                                    self._elapsed(
                                        started
                                    )
                                ),
                            )
                        )

                    # Warm L1 from Redis.
                    if (
                        self.config.backend
                        == CacheBackend.HYBRID
                    ):
                        self._memory_set(
                            entry
                        )

                    self._stats.hits += 1

                    return CacheLookupResult(
                        status=CacheStatus.HIT,
                        key=key,
                        embedding=list(
                            entry.embedding
                        ),
                        entry=entry,
                        source="redis",
                        latency_ms=(
                            self._elapsed(
                                started
                            )
                        ),
                    )

            self._stats.misses += 1

            return CacheLookupResult(
                status=CacheStatus.MISS,
                key=key,
                latency_ms=self._elapsed(
                    started
                ),
            )

        except Exception as exc:
            self._stats.errors += 1

            if not self.config.fail_open:
                raise EmbeddingCacheError(
                    "Embedding cache lookup "
                    "failed.",
                    code="CACHE_GET_FAILED",
                    cause=exc,
                ) from exc

            return CacheLookupResult(
                status=CacheStatus.ERROR,
                key=key,
                latency_ms=self._elapsed(
                    started
                ),
                error=str(exc),
            )

    # ==========================================================
    # Public write
    # ==========================================================

    def set(
        self,
        text: str,
        embedding: Sequence[
            float
        ],
        *,
        model_name: str,
        model_version: Optional[
            str
        ] = None,
        dimension: Optional[
            int
        ] = None,
        normalized: bool = False,
        namespace: Optional[
            str
        ] = None,
        ttl_seconds: Optional[
            int
        ] = None,
        metadata: Optional[
            dict[str, Any]
        ] = None,
    ) -> str:

        if (
            not text
            and not self.config
            .cache_empty_text
        ):
            return self.build_key(
                text,
                model_name=model_name,
                model_version=(
                    model_version
                ),
                dimension=dimension,
                normalized=normalized,
                namespace=namespace,
            )

        vector = [
            float(value)
            for value in embedding
        ]

        resolved_dimension = (
            dimension
            if dimension is not None
            else len(vector)
        )

        if (
            self.config
            .validate_dimension
            and resolved_dimension
            != len(vector)
        ):
            raise EmbeddingCacheError(
                "Embedding dimension does not "
                "match vector length.",
                code=(
                    "DIMENSION_MISMATCH"
                ),
            )

        key = self.build_key(
            text,
            model_name=model_name,
            model_version=model_version,
            dimension=resolved_dimension,
            normalized=normalized,
            namespace=namespace,
        )

        now = time.time()

        ttl = (
            self.config.ttl_seconds
            if ttl_seconds is None
            else ttl_seconds
        )

        expires_at = (
            now + ttl
            if ttl and ttl > 0
            else None
        )

        entry = EmbeddingCacheEntry(
            key=key,
            embedding=vector,
            text_hash=self.text_hash(
                text
            ),
            model_name=model_name,
            model_version=(
                model_version
            ),
            dimension=(
                resolved_dimension
            ),
            normalized=normalized,
            created_at=now,
            expires_at=expires_at,
            metadata=metadata or {},
        )

        try:
            if self.config.backend in {
                CacheBackend.MEMORY,
                CacheBackend.HYBRID,
            }:
                self._memory_set(
                    entry
                )

            if self.config.backend in {
                CacheBackend.REDIS,
                CacheBackend.HYBRID,
            }:
                self._redis_set(
                    entry,
                    ttl_seconds=ttl,
                )

            self._stats.writes += 1

            return key

        except Exception as exc:
            self._stats.errors += 1

            if not self.config.fail_open:
                raise EmbeddingCacheError(
                    "Embedding cache write "
                    "failed.",
                    code="CACHE_SET_FAILED",
                    cause=exc,
                ) from exc

            return key

    # ==========================================================
    # Batch API
    # ==========================================================

    def get_many(
        self,
        texts: Sequence[str],
        *,
        model_name: str,
        model_version: Optional[
            str
        ] = None,
        dimension: Optional[
            int
        ] = None,
        normalized: bool = False,
        namespace: Optional[
            str
        ] = None,
    ) -> BatchCacheLookup:

        embeddings: list[
            Optional[list[float]]
        ] = []

        missing_indices: list[
            int
        ] = []

        keys: list[str] = []

        hits = 0
        misses = 0

        for index, text in enumerate(
            texts
        ):
            result = self.get(
                text,
                model_name=model_name,
                model_version=(
                    model_version
                ),
                dimension=dimension,
                normalized=normalized,
                namespace=namespace,
            )

            keys.append(
                result.key
            )

            if result.hit:
                embeddings.append(
                    result.embedding
                )

                hits += 1
            else:
                embeddings.append(
                    None
                )

                missing_indices.append(
                    index
                )

                misses += 1

        return BatchCacheLookup(
            embeddings=embeddings,
            missing_indices=(
                missing_indices
            ),
            keys=keys,
            hits=hits,
            misses=misses,
        )

    def set_many(
        self,
        texts: Sequence[str],
        embeddings: Sequence[
            Sequence[float]
        ],
        *,
        model_name: str,
        model_version: Optional[
            str
        ] = None,
        dimension: Optional[
            int
        ] = None,
        normalized: bool = False,
        namespace: Optional[
            str
        ] = None,
        ttl_seconds: Optional[
            int
        ] = None,
        metadata: Optional[
            dict[str, Any]
        ] = None,
    ) -> list[str]:

        if len(texts) != len(
            embeddings
        ):
            raise EmbeddingCacheError(
                "texts and embeddings must "
                "have the same length.",
                code="BATCH_SIZE_MISMATCH",
            )

        keys: list[str] = []

        for text, embedding in zip(
            texts,
            embeddings,
        ):
            key = self.set(
                text,
                embedding,
                model_name=model_name,
                model_version=(
                    model_version
                ),
                dimension=dimension,
                normalized=normalized,
                namespace=namespace,
                ttl_seconds=(
                    ttl_seconds
                ),
                metadata=metadata,
            )

            keys.append(key)

        return keys

    # ==========================================================
    # Get-or-compute
    # ==========================================================

    def get_or_compute(
        self,
        text: str,
        compute: Any,
        *,
        model_name: str,
        model_version: Optional[
            str
        ] = None,
        dimension: Optional[
            int
        ] = None,
        normalized: bool = False,
        namespace: Optional[
            str
        ] = None,
        metadata: Optional[
            dict[str, Any]
        ] = None,
    ) -> list[float]:
        """
        Optional convenience method.

        `compute` can be:
            callable(text) -> embedding

        This is useful for small integrations, while EmbeddingService
        should normally own batched model inference.
        """

        result = self.get(
            text,
            model_name=model_name,
            model_version=model_version,
            dimension=dimension,
            normalized=normalized,
            namespace=namespace,
        )

        if (
            result.hit
            and result.embedding
            is not None
        ):
            return result.embedding

        try:
            embedding = compute(text)

            if hasattr(
                embedding,
                "embeddings",
            ):
                values = (
                    embedding.embeddings
                )

                if (
                    values
                    and isinstance(
                        values[0],
                        (
                            list,
                            tuple,
                        ),
                    )
                ):
                    embedding = values[0]
                else:
                    embedding = values

            if hasattr(
                embedding,
                "tolist",
            ):
                embedding = (
                    embedding.tolist()
                )

            vector = [
                float(value)
                for value in embedding
            ]

        except Exception as exc:
            raise EmbeddingCacheError(
                "Embedding computation "
                "failed.",
                code=(
                    "EMBEDDING_COMPUTE_FAILED"
                ),
                cause=exc,
            ) from exc

        self.set(
            text,
            vector,
            model_name=model_name,
            model_version=model_version,
            dimension=(
                dimension
                or len(vector)
            ),
            normalized=normalized,
            namespace=namespace,
            metadata=metadata,
        )

        return vector

    # ==========================================================
    # Delete
    # ==========================================================

    def delete(
        self,
        text: str,
        *,
        model_name: str,
        model_version: Optional[
            str
        ] = None,
        dimension: Optional[
            int
        ] = None,
        normalized: bool = False,
        namespace: Optional[
            str
        ] = None,
    ) -> bool:

        key = self.build_key(
            text,
            model_name=model_name,
            model_version=model_version,
            dimension=dimension,
            normalized=normalized,
            namespace=namespace,
        )

        deleted = False

        try:
            if self.config.backend in {
                CacheBackend.MEMORY,
                CacheBackend.HYBRID,
            }:
                deleted = (
                    self._memory_delete(
                        key
                    )
                    or deleted
                )

            if self.config.backend in {
                CacheBackend.REDIS,
                CacheBackend.HYBRID,
            }:
                deleted = (
                    self._redis_delete(
                        key
                    )
                    or deleted
                )

            if deleted:
                self._stats.deletes += 1

            return deleted

        except Exception as exc:
            self._stats.errors += 1

            if not self.config.fail_open:
                raise EmbeddingCacheError(
                    "Embedding cache delete "
                    "failed.",
                    code=(
                        "CACHE_DELETE_FAILED"
                    ),
                    cause=exc,
                ) from exc

            return False

    def clear_memory(
        self,
    ) -> None:

        with self._lock:
            count = len(
                self._memory
            )

            self._memory.clear()

            self._stats.deletes += (
                count
            )

            self._stats.memory_entries = 0

    # ==========================================================
    # Key generation
    # ==========================================================

    def build_key(
        self,
        text: str,
        *,
        model_name: str,
        model_version: Optional[
            str
        ] = None,
        dimension: Optional[
            int
        ] = None,
        normalized: bool = False,
        namespace: Optional[
            str
        ] = None,
    ) -> str:

        if not model_name:
            raise EmbeddingCacheError(
                "model_name is required.",
                code=(
                    "MISSING_MODEL_NAME"
                ),
            )

        text_digest = self.text_hash(
            text
        )

        payload: dict[str, Any] = {
            "text_hash": text_digest,
            "model": model_name,
            "dimension": dimension,
            "normalized": normalized,
        }

        if (
            self.config
            .include_model_version
        ):
            payload["version"] = (
                model_version
            )

        encoded = json.dumps(
            payload,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
        )

        identity_hash = (
            hashlib.sha256(
                encoded.encode("utf-8")
            ).hexdigest()
        )

        resolved_namespace = (
            namespace
            or self.config.namespace
        )

        return (
            f"{resolved_namespace}:"
            f"{self.config.redis_key_prefix}:"
            f"{identity_hash}"
        )

    def text_hash(
        self,
        text: str,
    ) -> str:

        value = text

        if (
            self.config
            .normalize_text_for_key
        ):
            value = self._normalize_text(
                value
            )

        return hashlib.sha256(
            value.encode("utf-8")
        ).hexdigest()

    @staticmethod
    def _normalize_text(
        text: str,
    ) -> str:
        """
        Disabled by default for legal documents.

        Exact source text should generally produce exact cache keys.
        """

        value = text.replace(
            "\r\n",
            "\n",
        )

        value = value.replace(
            "\r",
            "\n",
        )

        value = re_sub_whitespace(
            value
        )

        return value.strip()

    # ==========================================================
    # L1 Memory
    # ==========================================================

    def _memory_get(
        self,
        key: str,
    ) -> Optional[
        EmbeddingCacheEntry
    ]:

        with self._lock:
            entry = self._memory.get(
                key
            )

            if entry is None:
                return None

            if entry.expired:
                self._memory.pop(
                    key,
                    None,
                )

                self._stats.expired += 1
                self._stats.memory_entries = (
                    len(self._memory)
                )

                return None

            if (
                self.config
                .enable_memory_lru
            ):
                self._memory.move_to_end(
                    key
                )

            return entry

    def _memory_set(
        self,
        entry: EmbeddingCacheEntry,
    ) -> None:

        with self._lock:
            self._memory[
                entry.key
            ] = entry

            if (
                self.config
                .enable_memory_lru
            ):
                self._memory.move_to_end(
                    entry.key
                )

            while (
                len(self._memory)
                > self.config
                .memory_max_entries
            ):
                self._memory.popitem(
                    last=False
                )

            self._stats.memory_entries = (
                len(self._memory)
            )

    def _memory_delete(
        self,
        key: str,
    ) -> bool:

        with self._lock:
            existed = (
                key in self._memory
            )

            self._memory.pop(
                key,
                None,
            )

            self._stats.memory_entries = (
                len(self._memory)
            )

            return existed

    # ==========================================================
    # L2 Redis
    # ==========================================================

    def _redis_get(
        self,
        key: str,
    ) -> Optional[
        EmbeddingCacheEntry
    ]:

        if self.redis is None:
            raise EmbeddingCacheError(
                "Redis backend configured "
                "without redis_client.",
                code=(
                    "REDIS_NOT_CONFIGURED"
                ),
            )

        value = self.redis.get(
            key
        )

        if value is None:
            return None

        if isinstance(
            value,
            bytes,
        ):
            value = value.decode(
                "utf-8"
            )

        if isinstance(
            value,
            str,
        ):
            payload = json.loads(
                value
            )

        elif isinstance(
            value,
            dict,
        ):
            payload = value

        else:
            raise EmbeddingCacheError(
                "Unsupported Redis cache "
                "payload.",
                code=(
                    "INVALID_REDIS_PAYLOAD"
                ),
            )

        return (
            EmbeddingCacheEntry
            .from_dict(payload)
        )

    def _redis_set(
        self,
        entry: EmbeddingCacheEntry,
        *,
        ttl_seconds: Optional[
            int
        ],
    ) -> None:

        if self.redis is None:
            raise EmbeddingCacheError(
                "Redis backend configured "
                "without redis_client.",
                code=(
                    "REDIS_NOT_CONFIGURED"
                ),
            )

        payload = json.dumps(
            entry.to_dict(),
            separators=(",", ":"),
            ensure_ascii=False,
        )

        if (
            ttl_seconds
            and ttl_seconds > 0
        ):
            self.redis.set(
                entry.key,
                payload,
                ex=ttl_seconds,
            )

        else:
            self.redis.set(
                entry.key,
                payload,
            )

    def _redis_delete(
        self,
        key: str,
    ) -> bool:

        if self.redis is None:
            raise EmbeddingCacheError(
                "Redis backend configured "
                "without redis_client.",
                code=(
                    "REDIS_NOT_CONFIGURED"
                ),
            )

        result = self.redis.delete(
            key
        )

        try:
            return int(result) > 0
        except Exception:
            return bool(result)

    # ==========================================================
    # Validation
    # ==========================================================

    def _validate_entry(
        self,
        entry: EmbeddingCacheEntry,
        *,
        model_name: str,
        model_version: Optional[
            str
        ],
        dimension: Optional[
            int
        ],
        normalized: bool,
    ) -> bool:

        if entry.expired:
            return False

        if (
            entry.model_name
            != model_name
        ):
            return False

        if (
            self.config
            .include_model_version
            and entry.model_version
            != model_version
        ):
            return False

        if (
            self.config
            .validate_dimension
            and dimension is not None
        ):
            if (
                len(entry.embedding)
                != dimension
            ):
                return False

            if (
                entry.dimension
                is not None
                and entry.dimension
                != dimension
            ):
                return False

        if (
            entry.normalized
            != normalized
        ):
            return False

        if not self._valid_vector(
            entry.embedding
        ):
            return False

        return True

    @staticmethod
    def _valid_vector(
        vector: Sequence[
            float
        ],
    ) -> bool:

        if not vector:
            return False

        for value in vector:
            try:
                numeric = float(value)
            except (
                TypeError,
                ValueError,
            ):
                return False

            if not math.isfinite(
                numeric
            ):
                return False

        return True

    def _validate_config(
        self,
    ) -> None:

        if (
            self.config
            .memory_max_entries
            <= 0
        ):
            raise ValueError(
                "memory_max_entries must "
                "be > 0."
            )

        if (
            self.config.ttl_seconds
            < 0
        ):
            raise ValueError(
                "ttl_seconds cannot "
                "be negative."
            )

        if (
            self.config.backend
            in {
                CacheBackend.REDIS,
                CacheBackend.HYBRID,
            }
            and self.redis is None
            and not self.config.fail_open
        ):
            raise ValueError(
                "redis_client is required "
                "for Redis cache backend."
            )

    # ==========================================================
    # Statistics
    # ==========================================================

    @property
    def stats(
        self,
    ) -> EmbeddingCacheStats:

        with self._lock:
            self._stats.memory_entries = (
                len(self._memory)
            )

            return EmbeddingCacheStats(
                hits=self._stats.hits,
                misses=self._stats.misses,
                expired=(
                    self._stats.expired
                ),
                writes=self._stats.writes,
                deletes=(
                    self._stats.deletes
                ),
                errors=self._stats.errors,
                memory_entries=(
                    self._stats
                    .memory_entries
                ),
            )

    def reset_stats(
        self,
    ) -> None:

        with self._lock:
            self._stats = (
                EmbeddingCacheStats(
                    memory_entries=len(
                        self._memory
                    )
                )
            )

    # ==========================================================
    # Utilities
    # ==========================================================

    @staticmethod
    def _elapsed(
        started: float,
    ) -> float:

        return round(
            (
                time.perf_counter()
                - started
            )
            * 1000,
            3,
        )


def re_sub_whitespace(
    value: str,
) -> str:
    """
    Conservative whitespace normalization used only when explicitly
    enabled for cache-key generation.
    """

    import re

    value = re.sub(
        r"[ \t]+",
        " ",
        value,
    )

    value = re.sub(
        r"\n{3,}",
        "\n\n",
        value,
    )

    return value


def create_embedding_cache(
    *,
    redis_client: Any = None,
    backend: CacheBackend = (
        CacheBackend.MEMORY
    ),
    ttl_seconds: int = (
        7 * 24 * 60 * 60
    ),
    memory_max_entries: int = 10_000,
) -> EmbeddingCache:

    config = EmbeddingCacheConfig(
        backend=backend,
        ttl_seconds=ttl_seconds,
        memory_max_entries=(
            memory_max_entries
        ),
    )

    return EmbeddingCache(
        config=config,
        redis_client=redis_client,
    )